
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6),
    email VARCHAR(255) NOT NULL,
    first_name VARCHAR(255) NOT NULL,
    last_name VARCHAR(255) NOT NULL,
    password VARCHAR(100) NOT NULL,
    role VARCHAR(255) NOT NULL,
    CONSTRAINT users_role_check
        CHECK (role IN ('ADMIN', 'CUSTOMER'))
);

CREATE TABLE account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number VARCHAR(255),
    balance DOUBLE PRECISION,
    created_at TIMESTAMP(6),
    status VARCHAR(255),
    type VARCHAR(255),
    user_id BIGINT,
    CONSTRAINT account_status_check
        CHECK (status IN ('ACTIVE', 'FROZEN', 'CLOSED')),
    CONSTRAINT account_type_check
        CHECK (type IN ('CHECKING', 'SAVINGS', 'CREDIT')),
    CONSTRAINT fk_account_user
        FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE transaction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount DOUBLE PRECISION,
    created_at TIMESTAMP(6),
    description VARCHAR(255),
    type VARCHAR(255),
    from_account_id BIGINT,
    to_account_id BIGINT,
    CONSTRAINT transaction_type_check
        CHECK (type IN ('DEPOSIT', 'WITHDRAW', 'TRANSFER')),
    CONSTRAINT fk_transaction_from_account
        FOREIGN KEY (from_account_id) REFERENCES account(id),
    CONSTRAINT fk_transaction_to_account
        FOREIGN KEY (to_account_id) REFERENCES account(id)
);
